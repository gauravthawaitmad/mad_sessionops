"""
To use Google Sign-In on your frontend:

1. ADD GOOGLE SCRIPT (in HTML head):
   <script src="https://accounts.google.com/gsi/client" async></script>

2. ADD SIGN-IN BUTTON (React example):

   // GoogleSignInButton.jsx
   import { useEffect } from 'react';

   export function GoogleSignInButton({ onSuccess }) {
     useEffect(() => {
       // Initialize Google Sign-In
       window.google.accounts.id.initialize({
         client_id: 'YOUR_CLIENT_ID.apps.googleusercontent.com',
         callback: handleCredentialResponse,
       });

       // Render the button
       window.google.accounts.id.renderButton(
         document.getElementById('google-signin-button'),
         { theme: 'outline', size: 'large' }
       );
     }, []);

     async function handleCredentialResponse(response) {
       // response.credential is the ID token
       const result = await fetch('/api/v1/auth/google', {
         method: 'POST',
         headers: { 'Content-Type': 'application/json' },
         body: JSON.stringify({ id_token: response.credential }),
       });

       const data = await result.json();
       if (result.ok) {
         // Store tokens and redirect
         localStorage.setItem('access_token', data.tokens.access_token);
         localStorage.setItem('refresh_token', data.tokens.refresh_token);
         onSuccess(data.user);
       }
     }

     return <div id="google-signin-button"></div>;
   }

3. GOOGLE CLOUD CONSOLE SETUP:
   a. Go to https://console.cloud.google.com/apis/credentials
   b. Create OAuth 2.0 Client ID (Web application)
   c. Add authorized JavaScript origins:
      - http://localhost:3000 (development)
      - https://yourdomain.com (production)
   d. Copy Client ID to your .env file as GOOGLE_CLIENT_ID
"""
